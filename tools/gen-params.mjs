#!/usr/bin/env node
// Generates simulator tables and docs from spec/params.yaml + spec/pages.yaml.
// Validates the spec: unknown ids, overlapping bits, duplicate mnemonics.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (p) => YAML.parse(readFileSync(join(root, p), 'utf8'));
const spec = load('spec/params.yaml');
const pagesSpec = load('spec/pages.yaml');
const errors = [];

// ---- expand params
const params = spec.params.map((p) => ({ ...p, bank: null }));
for (const b of spec.modBanks) {
  const B = b.bank;
  const P = (o) => params.push({ conf: 'doc', bank: B, ...o });
  P({ id: `mod${B}_src`, name: `Bank ${B} source`, mn: 'So', byte: b.srcByte, shift: 4, width: 3, enum: 'modSource' });
  P({ id: `mod${B}_inv`, name: `Bank ${B} source invert`, mn: 'In', byte: b.srcByte, shift: 7, width: 1, activeLow: true });
  P({ id: `mod${B}_c_vel`, name: `Bank ${B} ctrl velocity`, mn: 'Uc', byte: b.srcByte, shift: 3, width: 1, activeLow: true });
  P({ id: `mod${B}_c_px`, name: `Bank ${B} ctrl +X`, mn: '+H', byte: b.srcByte, shift: 2, width: 1, activeLow: true });
  P({ id: `mod${B}_c_nx`, name: `Bank ${B} ctrl -X`, mn: '-H', byte: b.srcByte, shift: 1, width: 1, activeLow: true });
  P({ id: `mod${B}_c_press`, name: `Bank ${B} ctrl pressure`, mn: 'Pr', byte: b.srcByte, shift: 0, width: 1, activeLow: true });
  P({ id: `mod${B}_d_q`, name: `Bank ${B} dest VCF Q`, mn: 'oq', byte: b.destByte, shift: b.destShift + 3, width: 1, activeLow: true });
  P({ id: `mod${B}_d_fc`, name: `Bank ${B} dest VCF Fc`, mn: 'oF', byte: b.destByte, shift: b.destShift + 2, width: 1, activeLow: true });
  P({ id: `mod${B}_d_vco2`, name: `Bank ${B} dest VCO2`, mn: 'o2', byte: b.destByte, shift: b.destShift + 1, width: 1, activeLow: true });
  P({ id: `mod${B}_d_vco1`, name: `Bank ${B} dest VCO1`, mn: 'o1', byte: b.destByte, shift: b.destShift + 0, width: 1, activeLow: true });
  P({ id: `mod${B}_depth`, name: `Bank ${B} depth`, mn: 'dP', byte: b.depthByte, shift: 0, width: 8 });
  P({ id: `mod${B}_replace`, name: `Bank ${B} replace velocity by ${b.replaceName}`, mn: 'rP', byte: 0x1e, shift: b.replaceBit, width: 1, activeLow: true });
}
const byId = new Map();
for (const p of params) {
  if (byId.has(p.id)) errors.push(`duplicate id ${p.id}`);
  byId.set(p.id, p);
  if (p.enum && !spec.enums[p.enum]) errors.push(`${p.id}: unknown enum ${p.enum}`);
  if (p.shift + p.width > 8) errors.push(`${p.id}: bits exceed byte`);
  if (p.byte > 0x2c) errors.push(`${p.id}: byte beyond 45-byte program`);
  if (!/^[0-9A-Za-z+\- ]{1,2}$/.test(p.mn)) errors.push(`${p.id}: mnemonic '${p.mn}' not 7-seg renderable`);
}
// overlapping bits
const used = new Map();
for (const p of params) for (let i = 0; i < p.width; i++) {
  const k = p.byte * 8 + p.shift + i;
  if (used.has(k)) errors.push(`bit overlap byte ${p.byte.toString(16)} bit ${p.shift + i}: ${used.get(k)} / ${p.id}`);
  used.set(k, p.id);
}
// mnemonic uniqueness (bank params share mnemonics across banks, so compare with bank A only)
const mns = new Map();
for (const p of params.filter((p) => !p.bank || p.bank === 'A')) {
  const k = p.mn.toLowerCase();
  if (mns.has(k)) errors.push(`mnemonic '${p.mn}' used by ${mns.get(k)} and ${p.id}`);
  mns.set(k, p.id);
}

// ---- expand pages
const sub = (v, b) => (typeof v === 'string' ? v.replaceAll('{b}', b) : Array.isArray(v) ? v.map((x) => sub(x, b)) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, sub(x, b)])) : v);
const pages = [];
for (const pg of pagesSpec.pages) {
  if (pg.template) for (const b of pg.template) pages.push({ ...sub(pg, b), id: b, template: undefined });
  else pages.push(pg);
}
const checkParam = (where, id) => { if (!byId.has(id)) errors.push(`${where}: unknown param ${id}`); };
for (const pg of pages) {
  for (const [c, bnd] of Object.entries(pg.buttons ?? {})) {
    if (bnd.param) checkParam(`${pg.id}.${c}`, bnd.param);
    if (bnd.field) checkParam(`${pg.id}.${c}`, bnd.field.param);
  }
  for (const [c, bnd] of Object.entries(pg.pots ?? {})) checkParam(`${pg.id}.${c}`, bnd.param);
  for (const t of Object.values(pg.keypad?.targets ?? {})) checkParam(`${pg.id}.keypad`, t);
  if (pg.window?.param) checkParam(`${pg.id}.window`, pg.window.param);
}

if (errors.length) {
  console.error('spec errors:\n  ' + errors.join('\n  '));
  process.exit(1);
}

// ---- emit sim/src/gen/params.ts
const out = join(root, 'sim/src/gen/params.ts');
mkdirSync(dirname(out), { recursive: true });
const ts = `// GENERATED by tools/gen-params.mjs from spec/*.yaml — do not edit.
import type { ParamDef, EnumDef, PageDef } from '../types';
export const ENUMS: Record<string, EnumDef[]> = ${JSON.stringify(spec.enums, null, 1)};
export const PARAMS: ParamDef[] = ${JSON.stringify(params.map(({ id, name, mn, byte, shift, width, activeLow, enum: en, conf, note, bank }) => ({ id, name, mn, byte, shift, width, activeLow: !!activeLow, enum: en ?? null, conf: conf ?? 'doc', note: note ?? null, bank })), null, 1)};
export const PAGES: PageDef[] = ${JSON.stringify(pages, null, 1)};
`;
writeFileSync(out, ts);

// ---- emit docs/parameters.md
const hex = (n) => '$' + n.toString(16).toUpperCase().padStart(2, '0');
const rows = params
  .slice()
  .sort((a, b) => a.byte - b.byte || b.shift - a.shift)
  .map((p) => `| ${hex(p.byte)} | ${p.width === 1 ? p.shift : `${p.shift + p.width - 1}-${p.shift}`} | \`${p.id}\` | ${p.name} | \`${p.mn}\` | ${p.width === 1 ? (p.activeLow ? 'flag (active low)' : 'bit') : p.enum ? `enum ${p.enum}` : `0-${(1 << p.width) - 1}`} | ${p.conf ?? 'doc'} |`);
const pageRows = pages.map((pg) => `| ${pg.id} | ${pg.title} | ${Object.keys(pg.buttons ?? {}).length} | ${Object.keys(pg.pots ?? {}).length} | ${pg.keypad?.label ?? ''} |`);
writeFileSync(
  join(root, 'docs/parameters.md'),
  `# Voyetra Eight program parameters (45-byte program)

GENERATED from \`spec/params.yaml\` by \`npm run gen\`. Do not edit by hand.

Source: Voyetra-8 Program Format sheet (SysEx doc p.5-7). Single-bit flags are active low.
Bytes $28-$2C are undocumented (decoded in Phase 0). Confidence: doc = from the sheet, scan = sheet cut off, tbd = to verify.

| Byte | Bits | Id | Name | Mn | Type | Conf |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## Edit pages

| Page | Title | Buttons | Pots | Keypad |
|---|---|---|---|---|
${pageRows.join('\n')}
`,
);
console.log(`gen: ${params.length} params, ${pages.length} pages -> sim/src/gen/params.ts, docs/parameters.md`);
