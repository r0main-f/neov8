#!/usr/bin/env node
// Builds firmware/gen/rev4-tables.inc from the user's own stock ROM dump (tools/rom/build/rev4.bin).
// These are the calibrated response curves of the original instrument (envelope law, rate tables...).
// They are NOT stored in this repository: like an emulator, NeoV8 needs your ROM dump to be built.
//   node tools/rom/extract-roms.mjs   (once)   then   node tools/extract-tables.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { STOCK_TABLES } from './stock-tables.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const romFile = join(root, 'tools/rom/build/rev4.bin');
if (!existsSync(romFile)) {
  console.error('extract-tables: tools/rom/build/rev4.bin missing - run "npm run roms" with your stock ROM dump in "Voyetra 8 synths/"');
  process.exit(1);
}
const rom = readFileSync(romFile);
const sha1 = createHash('sha1').update(rom).digest('hex');
const EXPECTED = '91728a6243316a86408d82a8165ab19f8d4182f9';
if (sha1 !== EXPECTED) console.warn(`extract-tables: warning, rev4.bin sha1 ${sha1} is not the known Rev4 image`);

const TABLES = [...STOCK_TABLES];

const extra = process.argv.slice(2); // optional "label:addr:len" additions
for (const e of extra) {
  const [l, a, n] = e.split(':');
  TABLES.push([l, parseInt(a, 16), Number(n), 'extra']);
}

let out = `; GENERATED by tools/extract-tables.mjs from YOUR stock Rev4 ROM (sha1 ${sha1}).
; Do not commit: this file contains data from the original firmware. Rebuild with: npm run fw
`;
for (const [label, addr, len, comment] of TABLES) {
  // 256-byte tables page-aligned (segment PAGE, v8.cfg): indexed reads never cross a page, so their cycle cost does
  // not depend on where other code puts them (the envelope tick reads them many times)
  const page = len === 256;
  out += `\n; ${comment} (stock $${addr.toString(16).toUpperCase()}, ${len} bytes)\n`;
  if (page) out += `        .pushseg\n        .segment "PAGE"\n`;
  out += `${label}:\n`;
  for (let i = 0; i < len; i += 16) {
    const row = [...rom.subarray(addr - 0x8000 + i, addr - 0x8000 + Math.min(len, i + 16))].map((b) => '$' + b.toString(16).padStart(2, '0'));
    out += `        .byte ${row.join(',')}\n`;
  }
  if (page) out += `        .popseg\n`;
}
mkdirSync(join(root, 'firmware/gen'), { recursive: true });
writeFileSync(join(root, 'firmware/gen/rev4-tables.inc'), out);
console.log(`extract-tables: ${TABLES.length} tables -> firmware/gen/rev4-tables.inc`);
