"""Merge hand annotations (annotations.info: LABEL/RANGE blocks + 'DATA' overrides) with
trace.py coverage into a da65 info file.  Usage: gen-info.py rom.bin trace.json out.info ann1.info [ann2.info ...]"""
import sys, json, re
rom_path, tj, out = sys.argv[1:4]
d = json.load(open(tj))
ann = '\n'.join(open(p).read() for p in sys.argv[4:])
# hand RANGEs take precedence over traced coverage
hand = []
for m in re.finditer(r'RANGE\s*\{([^}]*)\}', ann):
    body = m.group(1)
    s = int(re.search(r'START\s+\$([0-9A-Fa-f]+)', body).group(1), 16)
    e = int(re.search(r'END\s+\$([0-9A-Fa-f]+)', body).group(1), 16)
    hand.append((s, e))
def covered(a): return any(s <= a <= e for s, e in hand)
code = bytearray(0x10000)
for s, e in d['ranges']:
    for a in range(s, e+1): code[a] = 1
lines = []
lines.append('# GENERATED by gen-info.py from ann/*.info + trace coverage. Edit ann/*.info.')
lines.append(f'global {{ inputname "{rom_path}"; startaddr $8000; cpu "6502"; comments 4; }};')
lines.append(ann)
a = 0x8000
while a <= 0xFFFF:
    if covered(a): a += 1; continue
    t = code[a]; s = a
    while a <= 0xFFFF and code[a] == t and not covered(a): a += 1
    typ = 'Code' if t else 'ByteTable'
    lines.append(f'RANGE {{ START ${s:04X}; END ${a-1:04X}; TYPE {typ}; }};')
open(out, 'w').write('\n'.join(lines) + '\n')
