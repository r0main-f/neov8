#!/usr/bin/env node
// Generates firmware/src/font.asm (ASCII -> 8279 segment byte) from the simulator's font (sim/src/font7.ts),
// so the firmware and the simulator show exactly the same glyphs.
// 8279 / panel wiring (stock SEGFONT $A080): bit 7=a 6=c 5=f 4=b 3=e 2=d 1=g 0=dp.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'sim/src/font7.ts'), 'utf8');
// evaluate the FONT table + aliases from the TS source (plain object literals only)
const body = src.slice(src.indexOf('const a = 1'), src.indexOf('export const DP'));
const FONT = new Function(`${body.replace(/: Record<string, number>/g, '')}; return FONT;`)();
const SIM_TO_PANEL = [7, 4, 6, 2, 3, 5, 1]; // sim bit (a..g) -> panel bit
const conv = (s) => SIM_TO_PANEL.reduce((acc, pb, i) => (s & (1 << i) ? acc | (1 << pb) : acc), 0);
const lines = [];
for (let c = 0x20; c < 0x80; c += 8) {
  const row = [];
  for (let k = c; k < c + 8; k++) row.push('$' + conv(FONT[String.fromCharCode(k)] ?? FONT['?']).toString(16).padStart(2, '0'));
  const txt = Array.from({ length: 8 }, (_, i) => String.fromCharCode(c + i)).join('').replace(/[^ -~]/g, '.');
  lines.push(`        .byte ${row.join(',')}   ; ${txt}`);
}
writeFileSync(join(root, 'firmware/src/font.asm'), `; GENERATED by tools/gen-font.mjs from sim/src/font7.ts - do not edit.
; ASCII $20-$7F -> 8279 display byte (bit 7=a 6=c 5=f 4=b 3=e 2=d 1=g 0=dp).
SEG_DP = $01
font:
${lines.join('\n')}
`);
console.log('gen-font: firmware/src/font.asm');
